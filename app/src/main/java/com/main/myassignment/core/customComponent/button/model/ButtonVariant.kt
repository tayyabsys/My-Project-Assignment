package com.main.myassignment.core.customComponent.button.model

/**
 * Defines the visual variant of a button
 *
 * @property Filled Standard button with gradient or solid background
 * @property Outlined Button with border and transparent/custom background
 * @property Text Borderless button with transparent background (text only)
 */
enum class ButtonVariant {
    Filled,
    Outlined,
    Text
}
